"""One-off asset optimisation for Pixel Pet (run once from the repo root).

Bitmaps in res/drawable/ are treated as mdpi and get upscaled by the screen
density when decoded; the original 960-2814 px images became 25-105 MB
bitmaps on xxhdpi phones. Everything is resized to roughly the size it is
actually drawn at and moved to drawable-nodpi/ so it is never rescaled.
"""
import os, re, glob
from PIL import Image, ImageDraw

RES = 'app/src/main/res'
D = f'{RES}/drawable'
NODPI = f'{RES}/drawable-nodpi'
os.makedirs(NODPI, exist_ok=True)


def fit(im, max_side):
    w, h = im.size
    s = max_side / max(w, h)
    if s >= 1:
        return im
    return im.resize((round(w * s), round(h * s)), Image.LANCZOS)


def save_webp(im, path, quality=90):
    im.save(path, 'WEBP', quality=quality, method=6)


# 1. Cat / dog / rabbit sprite frames: 960 px -> 384 px
for src in sorted(glob.glob(f'{D}/raw_*.webp')):
    save_webp(fit(Image.open(src).convert('RGBA'), 384), f'{NODPI}/{os.path.basename(src)}')
    os.remove(src)

# 3. Widget backgrounds: max height 1080 for the widget, 360 px thumbnails for the picker
for name, thumb in (('widget_background', 'bg_thumb_1'), ('widget_background_2', 'bg_thumb_2'),
                    ('widget_background_3', 'bg_thumb_3')):
    src = f'{D}/{name}.png'
    im = Image.open(src).convert('RGBA')
    big = im if im.height <= 1080 else im.resize((round(im.width * 1080 / im.height), 1080), Image.LANCZOS)
    save_webp(big, f'{NODPI}/{name}.webp')
    save_webp(fit(im, 360), f'{NODPI}/{thumb}.webp')
    os.remove(src)

# 4. Main screen artwork: avatar (80 dp) and pet icons (64 dp)
for name, side in (('ava.png', 320), ('pixel_kitty_icon.webp', 256), ('pixel_doggy_icon.webp', 256),
                   ('pixel_bunny_icon.webp', 256)):
    src = f'{D}/{name}'
    save_webp(fit(Image.open(src).convert('RGBA'), side), f'{NODPI}/{os.path.splitext(name)[0]}.webp')
    os.remove(src)

# 5. Launcher icon: 2048 px adaptive background -> 432 px (108 dp @ xxxhdpi) + legacy icons for API 24-25
icon_src = f'{RES}/mipmap-xxxhdpi/ic_launcher_custom_img.png'
icon = Image.open(icon_src).convert('RGBA')
icon.resize((432, 432), Image.LANCZOS).save(icon_src, optimize=True)
# Pre-O launchers show the whole bitmap: use the visible 72/108 centre with a rounded-square mask
edge = 2048 * 18 // 108
crop = icon.crop((edge, edge, 2048 - edge, 2048 - edge))
for bucket, px in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
    big = crop.resize((px * 4, px * 4), Image.LANCZOS)
    mask = Image.new('L', big.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, big.width - 1, big.height - 1), radius=big.width // 5, fill=255)
    out = Image.new('RGBA', big.size, (0, 0, 0, 0))
    out.paste(big, (0, 0), mask)
    out.resize((px, px), Image.LANCZOS).save(f'{RES}/mipmap-{bucket}/ic_launcher_custom.png', optimize=True)

